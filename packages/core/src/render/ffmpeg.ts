import { frameSize } from "../config";
import type { RenderSettings } from "../jobs";
import {
  timelineDuration,
  type AudioItem,
  type MediaItem,
  type Timeline,
  type Track,
} from "../timeline";

export type RenderAsset = {
  path: string;
  kind: "video" | "image" | "audio";
  hasAudio: boolean;
  duration: number | null;
};

export type RenderPlan = {
  args: string[];
  duration: number;
  width: number;
  height: number;
};

const FADE_SEC = 0.5;

function n(v: number): string {
  return (Math.round(v * 1000) / 1000).toString();
}

function even(v: number): number {
  return Math.max(2, Math.round(v / 2) * 2);
}

/** Escape a path for use inside a filtergraph option value. */
export function escapeFilterPath(p: string): string {
  return p.replace(/\\/g, "/").replace(/:/g, "\\:").replace(/'/g, "\\'").replace(/,/g, "\\,").replace(/\[/g, "\\[").replace(/\]/g, "\\]");
}

/**
 * Build FFmpeg arguments that render the timeline exactly as stored:
 *  - Visual items are composited onto a solid canvas in track order (lower position = further back),
 *    each scaled/cropped into its rect, placed at its timeline start, with optional fades.
 *  - Audio from video clips, narration and music is delayed to its start, volume-adjusted and mixed.
 *  - Captions and text overlays are burned in from an ASS file generated by buildAss().
 * Output: H.264 (yuv420p, high profile) + AAC 48 kHz in MP4 with faststart.
 */
export function buildRenderPlan(opts: {
  timeline: Timeline;
  assets: Record<string, RenderAsset>;
  settings: RenderSettings;
  assPath: string | null;
  outputPath: string;
  fontsDir?: string;
  preset?: string;
}): RenderPlan {
  const { timeline, assets, settings } = opts;
  const { width, height } = frameSize(timeline.aspectRatio, settings.resolution);
  const fps = timeline.fps;
  const duration = Math.max(0.5, timelineDuration(timeline));
  const tracks = new Map<string, Track>(timeline.tracks.map((t) => [t.id, t]));

  const inputs: string[] = [];
  const filters: string[] = [];
  let inputIndex = 0;

  // Input 0: background canvas.
  inputs.push("-f", "lavfi", "-i", `color=c=${timeline.background.replace("#", "0x")}:s=${width}x${height}:r=${fps}:d=${n(duration)}`);
  inputIndex++;

  const visual = timeline.items
    .filter((i): i is MediaItem => i.type === "video" || i.type === "image")
    .filter((i) => !tracks.get(i.trackId)?.hidden)
    .sort((a, b) => (tracks.get(a.trackId)?.position ?? 0) - (tracks.get(b.trackId)?.position ?? 0) || a.start - b.start);

  const audioLabels: string[] = [];
  let base = "[0:v]";
  let v = 0;

  for (const item of visual) {
    const asset = assets[item.assetId];
    if (!asset) throw new Error(`Missing asset ${item.assetId}`);
    const idx = inputIndex++;
    if (item.type === "image" || asset.kind === "image") {
      inputs.push("-loop", "1", "-framerate", String(fps), "-t", n(item.duration), "-i", asset.path);
    } else {
      inputs.push("-ss", n(item.sourceIn), "-t", n(item.duration), "-i", asset.path);
    }
    const rw = even(item.rect.w * width);
    const rh = even(item.rect.h * height);
    const rx = Math.round(item.rect.x * width);
    const ry = Math.round(item.rect.y * height);
    const chain: string[] = [];
    if (item.crop) {
      const c = item.crop;
      chain.push(`crop=w=iw*${n(c.w)}:h=ih*${n(c.h)}:x=iw*${n(c.x)}:y=ih*${n(c.y)}`);
    }
    if (item.fit === "cover") {
      chain.push(`scale=${rw}:${rh}:force_original_aspect_ratio=increase:flags=bicubic`, `crop=${rw}:${rh}`);
    } else {
      chain.push(
        `scale=${rw}:${rh}:force_original_aspect_ratio=decrease:flags=bicubic`,
        "format=yuva420p",
        `pad=${rw}:${rh}:(ow-iw)/2:(oh-ih)/2:color=black@0`,
      );
    }
    chain.push("setsar=1", `fps=${fps}`, "format=yuva420p");
    if (item.transitionIn === "fade") chain.push(`fade=t=in:st=0:d=${n(Math.min(FADE_SEC, item.duration / 2))}:alpha=1`);
    if (item.transitionOut === "fade") {
      const d = Math.min(FADE_SEC, item.duration / 2);
      chain.push(`fade=t=out:st=${n(item.duration - d)}:d=${n(d)}:alpha=1`);
    }
    chain.push(`setpts=PTS-STARTPTS+${n(item.start)}/TB`);
    filters.push(`[${idx}:v]${chain.join(",")}[vi${v}]`);
    const out = `[vb${v}]`;
    filters.push(
      `${base}[vi${v}]overlay=x=${rx}:y=${ry}:eof_action=pass:enable='between(t,${n(item.start)},${n(item.start + item.duration)})'${out}`,
    );
    base = out;
    v++;

    const track = tracks.get(item.trackId);
    if (item.type === "video" && asset.hasAudio && !item.muted && !track?.muted) {
      const vol = item.volume * (track?.volume ?? 1);
      if (vol > 0) {
        const label = `[a${audioLabels.length}]`;
        const delay = Math.round(item.start * 1000);
        filters.push(
          `[${idx}:a]aresample=48000,aformat=channel_layouts=stereo,asetpts=PTS-STARTPTS,volume=${n(vol)},adelay=${delay}|${delay}${label}`,
        );
        audioLabels.push(label);
      }
    }
  }

  const audioItems = timeline.items
    .filter((i): i is AudioItem => i.type === "audio")
    .filter((i) => !i.muted && !tracks.get(i.trackId)?.muted);
  for (const item of audioItems) {
    const asset = assets[item.assetId];
    if (!asset) throw new Error(`Missing asset ${item.assetId}`);
    const vol = item.volume * (tracks.get(item.trackId)?.volume ?? 1);
    if (vol <= 0) continue;
    const idx = inputIndex++;
    if (item.loop) inputs.push("-stream_loop", "-1");
    inputs.push("-ss", n(item.sourceIn), "-t", n(item.duration), "-i", asset.path);
    const chain = ["aresample=48000", "aformat=channel_layouts=stereo", "asetpts=PTS-STARTPTS", `volume=${n(vol)}`];
    if (item.fadeIn > 0) chain.push(`afade=t=in:st=0:d=${n(Math.min(item.fadeIn, item.duration))}`);
    if (item.fadeOut > 0) {
      const d = Math.min(item.fadeOut, item.duration);
      chain.push(`afade=t=out:st=${n(item.duration - d)}:d=${n(d)}`);
    }
    const delay = Math.round(item.start * 1000);
    chain.push(`adelay=${delay}|${delay}`);
    const label = `[a${audioLabels.length}]`;
    filters.push(`[${idx}:a]${chain.join(",")}${label}`);
    audioLabels.push(label);
  }

  // Captions / text overlays.
  let videoOut = base;
  if (opts.assPath) {
    const fonts = opts.fontsDir ? `:fontsdir=${escapeFilterPath(opts.fontsDir)}` : "";
    filters.push(`${base}ass=filename=${escapeFilterPath(opts.assPath)}${fonts}[vsub]`);
    videoOut = "[vsub]";
  }
  filters.push(`${videoOut}trim=duration=${n(duration)},format=yuv420p[vout]`);

  // Audio mix.
  if (audioLabels.length === 0) {
    inputs.push("-f", "lavfi", "-t", n(duration), "-i", "anullsrc=r=48000:cl=stereo");
    filters.push(`[${inputIndex++}:a]anull[amix]`);
  } else if (audioLabels.length === 1) {
    filters.push(`${audioLabels[0]}anull[amix]`);
  } else {
    filters.push(`${audioLabels.join("")}amix=inputs=${audioLabels.length}:duration=longest:normalize=0:dropout_transition=0[amix]`);
  }
  const post = ["apad", `atrim=duration=${n(duration)}`];
  if (settings.normalizeAudio && audioLabels.length > 0) post.push("loudnorm=I=-14:TP=-1.5:LRA=11", "aresample=48000");
  post.push("alimiter=limit=0.95");
  filters.push(`[amix]${post.join(",")}[aout]`);

  const args = [
    "-hide_banner",
    "-y",
    "-nostdin",
    ...inputs,
    "-filter_complex",
    filters.join(";\n"),
    "-map",
    "[vout]",
    "-map",
    "[aout]",
    "-c:v",
    "libx264",
    "-preset",
    opts.preset ?? "veryfast",
    "-crf",
    settings.resolution === "1080p" ? "20" : "22",
    "-profile:v",
    "high",
    "-pix_fmt",
    "yuv420p",
    "-r",
    String(fps),
    "-c:a",
    "aac",
    "-b:a",
    "192k",
    "-ar",
    "48000",
    "-ac",
    "2",
    "-movflags",
    "+faststart",
    "-t",
    n(duration),
    "-progress",
    "pipe:1",
    "-nostats",
    opts.outputPath,
  ];
  return { args, duration, width, height };
}

/** Parse `-progress pipe:1` output chunks into a 0..1 fraction. */
export function parseProgress(chunk: string, totalSec: number): number | null {
  const matches = [...chunk.matchAll(/out_time_(?:ms|us)=(\d+)/g)];
  const last = matches[matches.length - 1];
  if (!last) return null;
  const sec = Number(last[1]) / 1e6;
  return Math.max(0, Math.min(1, sec / Math.max(0.001, totalSec)));
}
